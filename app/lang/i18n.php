    /**
     * Carga las traducciones del idioma indicado con fallback a ES.
     *
     * Implementa un cache estático para evitar reconstruir el array
     * merged en cada petición dentro de la misma ejecución PHP.
     *
     * Cadena de fallback:
     *   1. Traducción en el idioma solicitado
     *   2. Traducción en español (base)
     *   3. La propia clave (nunca devuelve null)
     *
     * @param  string        $idioma  'es' | 'en' | 'pt'
     * @return \Closure              t(string $clave, int|null $n = null): string
     */
    public static function cargar(string $idioma): \Closure
    {
        // Normalizar: si el idioma no existe, caer a ES
        $idioma = in_array($idioma, self::idiomasDisponibles(), true) ? $idioma : 'es';

        // Construir (o recuperar del cache) el array merged
        if (!isset(self::$cache[$idioma])) {
            $base               = self::$traducciones['es']      ?? [];
            $override           = self::$traducciones[$idioma]   ?? [];
            // ES ya es la base; para ES el merge es idempotente
            self::$cache[$idioma] = array_merge($base, $override);
        }

        $lang = self::$cache[$idioma];

        return static function (string $clave, ?int $n = null) use ($lang): string {
            // Fallback final: devuelve la clave si no existe traducción
            $texto = $lang[$clave] ?? $clave;
            if ($n !== null) {
                $texto = str_replace('{n}', (string) $n, $texto);
            }
            return $texto;
        };
    }

    /**
     * Devuelve el array completo merged (base ES + override) para un idioma.
     * Útil para inyectar strings en JavaScript.
     *
     * @param  string $idioma
     * @return array<string, string>
     */
    public static function obtenerStrings(string $idioma): array
    {
        $idioma = in_array($idioma, self::idiomasDisponibles(), true) ? $idioma : 'es';

        if (!isset(self::$cache[$idioma])) {
            $base             = self::$traducciones['es']    ?? [];
            $override         = self::$traducciones[$idioma] ?? [];
            self::$cache[$idioma] = array_merge($base, $override);
        }

        return self::$cache[$idioma];
    }

    /**
     * Lista de idiomas disponibles.
     *
     * @return string[]
     */
    public static function idiomasDisponibles(): array
    {
        return array_keys(self::$traducciones);
    }

    /**
     * Limpia el cache interno (útil en tests unitarios).
     */
    public static function limpiarCache(): void
    {
        self::$cache = [];
    }
