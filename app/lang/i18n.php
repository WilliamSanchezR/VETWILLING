    /**
     * Carga las traducciones del idioma indicado.
     * Devuelve una función t($clave) que interpola {n} si se pasa $n.
     *
     * @param  string $idioma 'es' | 'en' | 'pt'
     * @return Closure  t(string $clave, int|null $n = null): string
     */
    public static function cargar(string $idioma): \Closure
    {
        $lang = self::$traducciones[$idioma] ?? self::$traducciones['es'];

        return function (string $clave, ?int $n = null) use ($lang): string {
            $texto = $lang[$clave] ?? $clave;
            if ($n !== null) {
                $texto = str_replace('{n}', (string) $n, $texto);
            }
            return $texto;
        };
    }

    /**
     * Devuelve el array completo de strings para un idioma (para el endpoint JS).
     */
    public static function obtenerStrings(string $idioma): array
    {
        return self::$traducciones[$idioma] ?? self::$traducciones['es'];
    }

    /**
     * Lista de idiomas disponibles.
     */
    public static function idiomasDisponibles(): array
    {
        return array_keys(self::$traducciones);
    }
